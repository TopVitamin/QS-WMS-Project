const pairs = <T extends Record<string, readonly [string, string]>>(v: T, lang: 0 | 1) =>
  Object.fromEntries(Object.entries(v).map(([k, p]) => [k, p[lang]])) as { [K in keyof T]: string }

const build = (lang: 0 | 1) => ({
  pdaQuery: pairs(query, lang),
  pdaMove: pairs(move, lang),
  pdaStocktake: pairs(stocktake, lang),
})
export const pdaInventoryZh = build(0)
export const pdaInventoryEn = build(1)
